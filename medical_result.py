import streamlit as st
import pandas as pd
import joblib



model = joblib.load(
    "medical_result_model.pkl"
)


st.set_page_config(
    page_title="Medical Result Prediction",
    page_icon="🩺",
    layout="centered"
)

st.title("🩺 Medical Result Prediction")

st.write(
    "Enter the patient measurements below "
    "to generate a model prediction."
)

age = st.number_input(
    "Age",
    min_value=1,
    max_value=120,
    value=50
)

gender = st.selectbox(
    "Gender",
    options=[0, 1],
    format_func=lambda x:
        "Female" if x == 0 else "Male"
)

heart_rate = st.number_input(
    "Heart Rate",
    min_value=20.0,
    max_value=200.0,
    value=80.0
)

systolic_bp = st.number_input(
    "Systolic Blood Pressure",
    min_value=40.0,
    max_value=250.0,
    value=120.0
)

diastolic_bp = st.number_input(
    "Diastolic Blood Pressure",
    min_value=30.0,
    max_value=160.0,
    value=80.0
)

blood_sugar = st.number_input(
    "Blood Sugar",
    min_value=0.0,
    max_value=600.0,
    value=120.0
)

ck_mb = st.number_input(
    "CK-MB",
    min_value=0.0,
    max_value=350.0,
    value=5.0
)

troponin = st.number_input(
    "Troponin",
    min_value=0.0,
    max_value=15.0,
    value=0.1
)

if st.button("Predict Result"):

    input_data = pd.DataFrame({
        "Age": [age],
        "Gender": [gender],
        "Heart rate": [heart_rate],
        "Systolic blood pressure": [systolic_bp],
        "Diastolic blood pressure": [diastolic_bp],
        "Blood sugar": [blood_sugar],
        "CK-MB": [ck_mb],
        "Troponin": [troponin]
    })

    prediction = model.predict(
        input_data
    )[0]

    probability = model.predict_proba(
        input_data
    )[0][1]

    if prediction == 1:

        st.error(
            "Prediction: Positive"
        )

    else:

        st.success(
            "Prediction: Negative"
        )

    st.write(
        f"Positive probability: "
        f"{probability:.2%}"
    )

st.warning(
    "This application is for educational purposes "
    "and is not a medical diagnostic tool."
)